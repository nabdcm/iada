/** يحدّد اسم المنطقة التشريحية الأقرب لنقطة النقر */
export function regionAt(view: BodyView, x: number, y: number): string {
  const list = view === "front" ? FRONT_REGIONS : BACK_REGIONS;
  // أول تطابق مباشر
  for (const r of list) {
    const [x1, y1, x2, y2] = r.box;
    if (x >= x1 && x <= x2 && y >= y1 && y <= y2) return r.ar;
  }
  // وإلا الأقرب مركزاً
  let best = list[0], bestD = Infinity;
  for (const r of list) {
    const [x1, y1, x2, y2] = r.box;
    const cx = (x1 + x2) / 2, cy = (y1 + y2) / 2;
    const d = (cx - x) ** 2 + (cy - y) ** 2;
    if (d < bestD) { bestD = d; best = r; }
  }
  return best.ar;
}

